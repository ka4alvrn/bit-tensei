function rollTrait() {
  const totalWeight = TRAITS.reduce((sum, t) => sum + t.weight, 0);
  let randomNum = Math.random() * totalWeight;

  for (let trait of TRAITS) {
    if (randomNum < trait.weight) return trait;
    randomNum -= trait.weight;
  }
  return TRAITS[0];
}
